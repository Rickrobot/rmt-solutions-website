#!/usr/bin/env python3
"""
Make the 16:9, 4:3 and 1:1 versions of every blog post's lead image.

WHY (Nov 2026 image SEO round): Google's Article guidance asks for the lead
image in all three aspect ratios, each at least 1200 px wide, so search
results, Discover and Google Images can each pick a large thumbnail that
fits. Site-wide robots already allows max-image-preview:large.

What it does:
  - reads each post's `image:` from lib/blogPosts.js
  - writes public/images/blog/lead/<slug>-16x9.webp, -4x3.webp and -1x1.webp
    (centre crops, scaled up to at least 1200 px wide where needed)
  - writes lib/blogLeadImages.js listing the slugs that have the set, which
    the BlogPosting schema and the sitemap read
  - skips posts that set their own `schemaImages:` (hand-made crops)

Run it after adding a post or changing a lead image:
    python3 scripts/blog-lead-images.py
Needs Python 3 with Pillow (already on the Mac Studio).
"""
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE = os.path.join(ROOT, "lib", "blogPosts.js")
OUT_DIR = os.path.join(ROOT, "public", "images", "blog", "lead")
LIB = os.path.join(ROOT, "lib", "blogLeadImages.js")

SIZES = {"16x9": (1600, 900), "4x3": (1200, 900), "1x1": (1200, 1200)}


def posts():
    src = open(PAGE, encoding="utf-8").read()
    start = src.index("export const blogPosts = {")
    end = src.index("\n};\n", start)
    body = src[start:end]
    keys = [(m.start(), m.group(1)) for m in re.finditer(r"\n  '([a-z0-9-]+)': \{", body)]
    for i, (pos, slug) in enumerate(keys):
        seg = body[pos: keys[i + 1][0] if i + 1 < len(keys) else len(body)]
        img = re.search(r"\n    image: '([^']+)'", seg)
        own = "\n    schemaImages:" in seg
        yield slug, (img.group(1) if img else None), own


def crop_to(im, w, h):
    sw, sh = im.size
    target = w / h
    if sw / sh > target:
        nw = int(round(sh * target))
        x = (sw - nw) // 2
        box = (x, 0, x + nw, sh)
    else:
        nh = int(round(sw / target))
        y = (sh - nh) // 2
        box = (0, y, sw, y + nh)
    return im.crop(box).resize((w, h), Image.LANCZOS)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    done = []
    for slug, img, own in posts():
        if own:
            print("skip (own schemaImages):", slug)
            continue
        if not img:
            print("skip (no image):", slug)
            continue
        path = os.path.join(ROOT, "public", img.lstrip("/"))
        if not os.path.exists(path):
            print("MISSING lead image:", slug, img)
            continue
        im = Image.open(path).convert("RGB")
        for name, (w, h) in SIZES.items():
            crop_to(im, w, h).save(os.path.join(OUT_DIR, f"{slug}-{name}.webp"), quality=86, method=6)
        done.append(slug)
        print("made:", slug)
    lines = [
        "// GENERATED by scripts/blog-lead-images.py - do not edit by hand.",
        "// Slugs whose lead image has 16:9, 4:3 and 1:1 versions at",
        "// /images/blog/lead/<slug>-<ratio>.webp (Google Article image guidance).",
        "export const BLOG_LEAD_IMAGE_SLUGS = new Set([",
    ] + [f"  '{s}'," for s in sorted(done)] + [
        "])",
        "",
        "export const blogLeadImageSet = (slug) =>",
        "  BLOG_LEAD_IMAGE_SLUGS.has(slug)",
        "    ? ['16x9', '4x3', '1x1'].map((r) => `/images/blog/lead/${slug}-${r}.webp`)",
        "    : []",
        "",
    ]
    open(LIB, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{len(done)} posts done; wrote {LIB}")


if __name__ == "__main__":
    sys.exit(main())
